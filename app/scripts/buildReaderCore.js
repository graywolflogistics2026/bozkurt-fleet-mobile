// Bundles app/src/settlementReader/core.ts (and the pure app modules it
// imports: the gate, the statement checks, date parsing, ...) into ONE ES
// module the ai-import Edge Function imports. Run after changing any of
// them:   npm run build:reader
// The output is committed; app/src/settlementReader/__tests__/coreBundle.test.ts
// fails when it is stale.
const path = require('path');
const fs = require('fs');
const esbuild = require('esbuild');

const APP = path.join(__dirname, '..');
const ENTRY = path.join(APP, 'src/settlementReader/core.ts');
const OUT = path.join(APP, '../supabase/functions/ai-import/reader/core.gen.js');
const BANNER = '// GENERATED by app/scripts/buildReaderCore.js from app/src/settlementReader/core.ts. Do not edit.\n// deno-lint-ignore-file';

function buildReaderCore(format = 'esm') {
  const result = esbuild.buildSync({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format,
    platform: 'neutral',
    target: 'es2022',
    charset: 'utf8',
    legalComments: 'none',
    alias: { '@': APP },
    banner: { js: BANNER },
    logLevel: 'silent',
    absWorkingDir: APP,
  });
  // Paths in esbuild's region comments are relative to the cwd; make them
  // stable whatever directory the build runs from.
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

module.exports = { buildReaderCore, OUT };

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, buildReaderCore());
  console.log('wrote', path.relative(process.cwd(), OUT));
}
